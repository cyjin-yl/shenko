export function resolveLocale(requested: string | readonly string[]): UiLocale {
  for (const value of typeof requested === 'string' ? [requested] : requested) {
    const language = value.toLowerCase().split(/[-_]/)[0];
    if (language === 'zh') return 'zh-CN';
    if (language === 'en') return 'en';
  }
  return DEFAULT_LOCALE;
}

export function preferredLocale(): UiLocale {
  return typeof navigator === 'undefined' ? DEFAULT_LOCALE
    : resolveLocale(navigator.languages?.length ? navigator.languages : navigator.language ?? DEFAULT_LOCALE);
}

export function message<K extends MessageId>(message_id: K, ...[values]: MessageArguments<K>): UiMessage {
  return { message_id, values: values ?? {} };
}

/** Missing translations fall back per ID to zh-CN, in a fixed order. */
export function resolveMessage(value: LocalizedText | null = null, locale: UiLocale = preferredLocale()): string {
  if (value == null) return '';
  if (typeof value === 'string') return value;
  const template = (locale === 'en' ? en[value.message_id] : undefined) ?? zhCN[value.message_id];
  return template.replace(/\{([^{}]+)\}/g, (placeholder, key: string) => Object.hasOwn(value.values, key)
    ? String(value.values[key]) : placeholder);
}

export function text<K extends MessageId>(id: K, ...args: MessageArguments<K>): string {
  return resolveMessage(message(id, ...args));
}
